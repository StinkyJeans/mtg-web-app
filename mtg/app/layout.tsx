import type { Metadata } from "next";
import { Atkinson_Hyperlegible_Next, Inter, Geist_Mono, Rajdhani } from "next/font/google";
import "mana-font/css/mana.css";
import "./globals.css";
import UserBar from "./UserBar";
import { THEME_BOOT_SCRIPT } from "@/lib/theme";

// Inter: made for reading text on screens, clear at small sizes.
const inter = Inter({
  variable: "--font-inter",
  subsets: ["latin"],
  display: "swap",
});

// Atkinson Hyperlegible Next: drawn so that similar letters (I, l, 1, O, 0) stay clearly different. Used for text in dark mode, where thin text on a dark page is hardest to read.
const atkinson = Atkinson_Hyperlegible_Next({
  variable: "--font-atkinson",
  subsets: ["latin"],
  display: "swap",
});

// Rajdhani: a crisp, slightly squared game-interface face for labels, names and numbers.
const rajdhani = Rajdhani({
  variable: "--font-rajdhani",
  subsets: ["latin"],
  weight: ["500", "600", "700"],
  display: "swap",
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      suppressHydrationWarning
      className={`${inter.variable} ${atkinson.variable} ${rajdhani.variable} ${geistMono.variable} h-full antialiased`}
    >
      <head>
        <script dangerouslySetInnerHTML={{ __html: THEME_BOOT_SCRIPT }} />
      </head>
      <body className="min-h-full flex flex-col">
        <UserBar />
        {children}
      </body>
    </html>
  );
}
